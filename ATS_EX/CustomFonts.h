//
//  - Each of the 6 bytes corresponds to a vertical column of 8 pixels.
//  - Within each byte, Bit 0 represents the top pixel and Bit 7 the bottom pixel.
//
// --- Visual Example: Character 'A' ---
//
// 1. Array Data for 'A' (ASCII 0x41):
//    {0x7E, 0x11, 0x11, 0x11, 0x7E, 0x00}
//
// 2. Binary Representation (columns are read top-to-bottom):
//    Column 1: 0x7E = 01111110
//    Column 2: 0x11 = 00010001
//    Column 3: 0x11 = 00010001
//    Column 4: 0x11 = 00010001
//    Column 5: 0x7E = 01111110
//    Column 6: 0x00 = 00000000  (This column provides spacing between characters)
//
// 3. Pixel Grid Layout ('#' = Pixel ON, '.' = Pixel OFF):
//
//           <---- 6 pixels wide ---->
//           Col  1  2  3  4  5  6
//          +------------------------+
//    Bit 0 |   .  #  #  #  .  .   | ^
//    Bit 1 |   #  .  .  .  #  .   | |
//    Bit 2 |   #  .  .  .  #  .   | |
//    Bit 3 |   #  #  #  #  #  .   | 8
//    Bit 4 |   #  .  .  .  #  .   | pixels
//    Bit 5 |   #  .  .  .  #  .   | high
//    Bit 6 |   #  .  .  .  #  .   | |
//    Bit 7 |   .  .  .  .  .  .   | v
//          +------------------------+
//
//    This translates to the character you see on the screen:
//
//     .###.
//     #...#
//     #...#
//     #####
//     #...#
//     #...#
//     #...#
//     .....
//
// =======================================================================================

